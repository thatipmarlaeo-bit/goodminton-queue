-- -----------------------------------------------------------------------------
-- ⚠️ ข้อมูลจริงจากโปรเจกต์ยืนยันแล้วว่า schema ออกแบบให้ใช้ "สองตาราง identity"
--    ร่วมกัน -> **ห้าม drop ตารางใดตารางหนึ่ง**
--
--   * profiles        <- FK ของ queue_members/daily_checkins ชี้มา +
--                        live_courts_view อิงอยู่ (ตัวตนจริง / who-is-inside)
--   * user_profiles   <- active_queues_view สร้างอยู่บนตารางนี้
--                        (รายชื่อ/avatar ในคิวที่ผู้เล่นเห็น)
--
-- การ "ลบ/รวม" จะต้องเขียน view ทั้งสองใหม่อิงตารางเดียว ซึ่งนิยามไม่ได้อยู่
-- ใน repo -> ไม่ควรทำ เก็บทั้งสองไว้ (ข้อมูลยังอยู่ครบ ใช้งานได้ตามปกติ)
--
-- หมายเหตุ: หากเหตุการณ์ก่อนหน้าอาจรัน merge user_profiles->profiles ไปแล้ว
-- ("on conflict do nothing" = ไม่ทับของเดิม ปลอดภัย) ไม่เป็นไร ไม่มีผลเสีย
-- =============================================================================
-- ไม่มีคำสั่ง DML/Drop ในไฟล์นี้ (ตั้งใจ เหตุผลข้างบน)
select 'keep both tables (profiles + user_profiles) — do NOT drop' as note;
