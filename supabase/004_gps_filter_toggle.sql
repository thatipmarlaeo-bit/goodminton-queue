-- 004_gps_filter_toggle.sql
-- ตาราง system_settings + ค่าเริ่มต้นสำหรับปุ่ม "ปิดกรอง GIS" (หน้าแอดมิน)
-- -----------------------------------------------------------------------------
-- วิธีใช้: เปิด Supabase Dashboard -> SQL Editor -> New query -> วางโค้ดนี้ -> Run
--
-- ทำให้ใครใช้งาน: สวิตช์นี้อยู่บนหน้า /admin เท่านั้น (หลังกรอก PIN)
-- เมื่อแอดมินปิดกรอง -> ผู้เล่นทุกหน้าจอจะถือว่าทุกคนอยู่ "ในสนาม" เสมอ
-- (สร้าง/แจมคิว + check-in ได้ทันที ไม่เช็กพิกัด) สำหรับการทดสอบ
--
-- หมายเหตุ: ระบบไม่มี real auth ตัวจริง การอนุญาตตรงนี้คือหน้าจอ/UI เป็นตัวกัน
-- (เหมือนฟีเจอร์อื่น ๆ ทั้งหมดของแอป) ไม่ใช่ policy ระดับฐานข้อมูล
-- =============================================================================

-- 1) ตารางคีย์-ค่า สำหรับการตั้งค่าระบบทั้งหลาย
create table if not exists public.system_settings (
  key        text primary key,
  value      text,
  updated_at timestamptz default now()
);

-- 2) ค่าเริ่มต้น: กรอง GIS ตามพิกัด "เปิดอยู่"
insert into public.system_settings (key, value)
values ('gps_filter_enabled', 'true')
on conflict (key) do nothing;

-- 3) ให้ SPA (anon/authenticated) อ่าน และแอดมินฝั่ง UI เขียนได้
grant select, insert, update on table public.system_settings to anon, authenticated;

-- 4) ปิด RLS สำหรับตารางนี้
--    เหตุผล: แอปนี้ไม่มี real auth (ตัวตนคือ device_id ฝั่ง UI) การอนุญาตคือ
--    PIN/UI หน้าแอดมิน ตามโมเดลเดียวกับตารางอื่น ๆ ถ้าสร้างผ่าน Table Editor
--    ซึ่งเปิด RLS ให้อัตโนมัติ ตรงนี้จะปิดให้เพื่อให้แอปเขียนได้ทันที
alter table public.system_settings disable row level security;

-- 5) บังคับให้ PostgREST โหลด schema ใหม่ กัน error "schema cache" หลังเพิ่งสร้างตาราง
notify pgrst, 'reload schema';

-- -----------------------------------------------------------------------------
-- ค่าที่ใช้: 'true'  = กรองกรองพิกัดตามปกติ (ผู้เล่นต้องอยู่ในรัศมีสนาม)
--            'false' = ปิดกรองทั่วทั้งสนาม (ทุกคนทำรายการได้เหมือนอยู่ในสนาม)
-- -----------------------------------------------------------------------------